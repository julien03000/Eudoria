<#
.SYNOPSIS
    Generates one of the core's signing keys and stores it in the repository's .env file.
.DESCRIPTION
    Two distinct ES256 keys (ECDSA P-256, PKCS#8, Base64), never displayed:
    - by default, the access-token key, written to IDENTITY_TOKEN_SIGNING_KEY;
    - with -EntryTickets, the world entry ticket key (ADR-0007), written to IDENTITY_ENTRY_TICKET_SIGNING_KEY.
    An existing key is kept unless -Force is given. Replacing the access-token key invalidates every
    access token already issued (everyone has to log in again); replacing the entry ticket key
    invalidates the tickets in flight (60 s at most) until world servers download the new public key.
.EXAMPLE
    .\tools\dev\new-signing-key.ps1                  # once, after creating .env
    .\tools\dev\new-signing-key.ps1 -EntryTickets    # once, for the entry tickets (sub-step 1.6)
    .\tools\dev\new-signing-key.ps1 -Force           # replace the access-token key
#>
[CmdletBinding()]
param(
    [switch]$EntryTickets,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'DotEnv.ps1')

if ($EntryTickets) {
    $keyName = 'IDENTITY_ENTRY_TICKET_SIGNING_KEY'
    $comment = '# --- Core: world entry ticket signing key (ES256), generated by tools/dev/new-signing-key.ps1 -EntryTickets ---'
    $replaceWarning = 'tickets in flight become invalid'
} else {
    $keyName = 'IDENTITY_TOKEN_SIGNING_KEY'
    $comment = '# --- Core: access-token signing key (ES256), generated by tools/dev/new-signing-key.ps1 ---'
    $replaceWarning = 'everyone will have to log in again'
}

$envValues = Read-EudoriaDotEnv   # fails early with a clear message if .env is missing or incomplete
if ($envValues.ContainsKey($keyName) -and $envValues[$keyName] -ne '' -and -not $Force) {
    Write-Host "$keyName is already set in .env: kept. Use -Force to replace it ($replaceWarning)."
    exit 0
}

# Captured in memory, never printed.
$key = (& dotnet run --file (Join-Path $PSScriptRoot 'NewSigningKey.cs') | Out-String).Trim()
if ($LASTEXITCODE -ne 0 -or $key -notmatch '^[A-Za-z0-9+/]+={0,2}$') {
    throw "Key generation failed (exit code $LASTEXITCODE)."
}

$lines = [System.Collections.Generic.List[string]]::new()
$replaced = $false
foreach ($line in [System.IO.File]::ReadAllLines($script:EnvFile)) {
    if ($line.Trim().StartsWith("$keyName=")) {
        $lines.Add("$keyName=$key")
        $replaced = $true
    } else {
        $lines.Add($line)
    }
}
if (-not $replaced) {
    $lines.Add('')
    $lines.Add($comment)
    $lines.Add("$keyName=$key")
}

# UTF-8 without BOM: docker compose also reads this file.
[System.IO.File]::WriteAllLines($script:EnvFile, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Host "$keyName written to .env (value not displayed)."
