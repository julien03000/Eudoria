<#
.SYNOPSIS
    Builds the list of common passwords refused by the EUDORIA core (sub-step 1.4).
.DESCRIPTION
    Reads public lists of leaked passwords (downloaded by hand beforehand, never committed),
    keeps only the entries the core could otherwise accept, and writes the filtered list embedded
    in the Identity module. Each entry is normalized exactly as the core compares passwords:
    Unicode NFKC, then lower case (invariant). Kept: 12 to 128 code points (the registration
    rules), no control character, valid text. Output: one entry per line, UTF-8 without BOM, LF,
    sorted (ordinal), no duplicates. The sources and their SHA-256 are written to a side file.

    Sources used in 1.4 (owner decision, 2026-11-24), from https://github.com/danielmiessler/SecLists
    (MIT licence):
      Passwords/Common-Credentials/Pwdb_top-1000000.txt
      Passwords/Common-Credentials/Language-Specific/French-common-password-list-top-20000.txt
.EXAMPLE
    .\tools\dev\build-password-blocklist.ps1 -Source E:\Dev\_downloads\seclists\Pwdb_top-1000000.txt, E:\Dev\_downloads\seclists\French-common-password-list-top-20000.txt
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [string[]] $Source
)

$ErrorActionPreference = 'Stop'

$repoRoot = Resolve-Path (Join-Path $PSScriptRoot '..\..')
$passwordsDir = Join-Path $repoRoot 'core\src\Eudoria.Core.Identity\Passwords'
$output = Join-Path $passwordsDir 'common-passwords.txt'
$sourcesFile = Join-Path $passwordsDir 'common-passwords.SOURCES.md'

$minCodePoints = 12
$maxCodePoints = 128

# Strict UTF-8: a line that is not valid UTF-8 is skipped rather than turned into replacement characters.
$utf8Strict = New-Object System.Text.UTF8Encoding($false, $true)
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$entries = New-Object 'System.Collections.Generic.HashSet[string]' ([System.StringComparer]::Ordinal)
$sourceLines = @()

foreach ($path in $Source) {
    $fullPath = (Resolve-Path $path).Path
    $bytes = [System.IO.File]::ReadAllBytes($fullPath)
    $read = 0
    $kept = 0

    # Split on LF in bytes, decode each line on its own (one bad line must not spoil the file).
    $start = 0
    while ($start -lt $bytes.Length) {
        $i = [System.Array]::IndexOf($bytes, [byte]10, $start)
        if ($i -lt 0) { $i = $bytes.Length }
        $length = $i - $start
        if ($length -gt 0 -and $bytes[$start + $length - 1] -eq 13) { $length-- }
        $lineStart = $start
        $start = $i + 1
        if ($length -le 0) { continue }
        $read++

        try {
            $line = $utf8Strict.GetString($bytes, $lineStart, $length)
            # Hashcat notation for entries with unusual bytes: $hex[61c3a7] = the UTF-8 bytes 61 c3 a7.
            if ($line -match '^\$HEX\[([0-9a-fA-F]*)\]$' -and $Matches[1].Length % 2 -eq 0) {
                $hex = $Matches[1]
                $raw = New-Object byte[] ($hex.Length / 2)
                for ($j = 0; $j -lt $raw.Length; $j++) { $raw[$j] = [System.Convert]::ToByte($hex.Substring($j * 2, 2), 16) }
                $line = $utf8Strict.GetString($raw)
            }
            $normalized = $line.Normalize([System.Text.NormalizationForm]::FormKC).ToLowerInvariant()
        }
        catch {
            continue # invalid UTF-8 or lone surrogate
        }

        if ($normalized -match '\p{Cc}') { continue }
        $codePoints = $normalized.Length
        foreach ($c in $normalized.ToCharArray()) { if ([char]::IsLowSurrogate($c)) { $codePoints-- } }
        if ($codePoints -lt $minCodePoints -or $codePoints -gt $maxCodePoints) { continue }

        if ($entries.Add($normalized)) { $kept++ }
    }

    $hash = (Get-FileHash -Algorithm SHA256 $fullPath).Hash.ToLowerInvariant()
    $sourceLines += "| ``$(Split-Path $fullPath -Leaf)`` | $($bytes.Length) | $read | $kept | ``$hash`` |"
    Write-Host ("{0}: {1} lines read, {2} new entries kept" -f (Split-Path $fullPath -Leaf), $read, $kept)
}

$sorted = New-Object 'System.Collections.Generic.List[string]' (, [string[]]@($entries))
$sorted.Sort([System.StringComparer]::Ordinal)
[System.IO.File]::WriteAllText($output, (($sorted -join "`n") + "`n"), $utf8NoBom)

$outputHash = (Get-FileHash -Algorithm SHA256 $output).Hash.ToLowerInvariant()
$outputSize = (Get-Item $output).Length
$doc = @(
    '# Common passwords list - sources',
    '',
    'Generated by `tools/dev/build-password-blocklist.ps1` (do not edit `common-passwords.txt` by hand).',
    'Sources: [SecLists](https://github.com/danielmiessler/SecLists), MIT licence, folder `Passwords/Common-Credentials`.',
    'The origin of the French list is not documented by SecLists.',
    '',
    'Each entry: Unicode NFKC, lower case (invariant), 12 to 128 code points, no control character.',
    '',
    '| Source file | Bytes | Lines read | New entries kept | SHA-256 |',
    '|---|---|---|---|---|'
) + $sourceLines + @(
    '',
    "Result: **$($sorted.Count) entries**, $outputSize bytes, SHA-256 ``$outputHash``."
)
[System.IO.File]::WriteAllText($sourcesFile, (($doc -join "`n") + "`n"), $utf8NoBom)

Write-Host ("Written {0}: {1} entries, {2} bytes" -f $output, $sorted.Count, $outputSize)
